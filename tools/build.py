# Assemble ../index.html (family), ../open/index.html (no photos) and ../sw.js from template.html + rules.js + faces.js + levels50.json (+ level-map.json)
import pathlib,json,hashlib
from urllib.parse import quote
h=pathlib.Path(__file__).parent
t=(h/'template.html').read_text()
rules=(h/'rules.js').read_text().replace("if(typeof module!=='undefined')module.exports={parseLevel,stepState,stateKey,solve,hintMove,DIRS};\n","")
levels=(h/'levels50.json').read_text()
n=len(json.loads(levels))
# old->new level index map for the leaderboard rows and local progress written before the v5 set; identity if no map file
if (h/'level-map.json').exists():
    m={k:v for k,v in json.load(open(h/'level-map.json')).items() if not k.startswith('_')}
else:
    m={str(i):i for i in range(n)}
base=t.replace('/*RULES*/',rules).replace('/*LEVELS*/[]',levels).replace('/*LEVELMAP*/{}',json.dumps(m,separators=(',',':')))
# family
fam=base.replace('/*FACES*/',(h/'faces.js').read_text().strip())
(h.parent/'index.html').write_text(fam)
# open: generic avatars, separate board, no unlock-all
emo=['🐍','🍎','🐸','🦎','🐢','🐛','🌱','🍏'];cols=['#2f7d3a','#e0493a','#3a8fd1','#e3a51f','#7b5ea7','#d86b2a','#2aa39a','#b03a6b']
def av(e,c):
    svg=f"<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 100 100'><circle cx='50' cy='50' r='50' fill='{c}'/><text x='50' y='66' font-size='52' text-anchor='middle'>{e}</text></svg>"
    return 'data:image/svg+xml;utf8,'+quote(svg,safe="/:=,'() <>").replace('#','%23')
faces='const FACES='+json.dumps([av(e,c) for e,c in zip(emo,cols)])+';'
op=base.replace('/*FACES*/',faces)
def rep(s,a,b):
    assert a in s,'missing in template: '+a
    return s.replace(a,b)
op=rep(op,"const FACE_NAMES=['','','','','','','Iain'];","const FACE_NAMES=['','','','','','','',''];")
op=rep(op,"const p={id:'p'+Date.now().toString(36),","const p={id:'pub-'+Date.now().toString(36),")
op=rep(op,"const PUB=false;","const PUB=true;")
op=rep(op,"const open=/^andrew$/i.test(p.name.trim())?LEVELS.length:unlockedUpTo(p);","const open=unlockedUpTo(p);")
op=rep(op,'<h2>Family Board</h2>','<h2>Leaderboard</h2>')
op=rep(op,'<span>Family Board</span>','<span>Leaderboard</span>')
op=op.replace('counts on the Family Board','counts on the Leaderboard')
op=rep(op,'<h2>Pick your face</h2>','<h2>Pick an avatar</h2>')
op=rep(op,'href="manifest.json"','href="../manifest.json"').replace('href="apple-touch-icon.png"','href="../apple-touch-icon.png"')
op=rep(op,"const KEY='orchard.v1';","const KEY='orchard.open.v1';")
assert 'Iain' not in op and '/9j/' not in op and 'pub-' in op and 'Family Board' not in op
(h.parent/'open').mkdir(exist_ok=True)
(h.parent/'open'/'index.html').write_text(op)
# service worker: offline + installable. Version follows the page content so every deploy refreshes the cache.
v='oc-'+hashlib.sha1((fam+op).encode()).hexdigest()[:10]
sw="""// Orchard Climber service worker (generated by tools/build.py; do not edit)
const V='%s';const CORE=['/','/open','/manifest.json','/icon-192.png','/icon-512.png','/apple-touch-icon.png'];
self.addEventListener('install',e=>{e.waitUntil(caches.open(V).then(c=>c.addAll(CORE)).then(()=>self.skipWaiting()));});
self.addEventListener('activate',e=>{e.waitUntil(caches.keys().then(ks=>Promise.all(ks.filter(k=>k.startsWith('oc-')&&!k.startsWith(V)).map(k=>caches.delete(k)))).then(()=>self.clients.claim()));});
self.addEventListener('fetch',e=>{if(e.request.method!=='GET')return;const u=new URL(e.request.url);
  if(u.origin===location.origin){ // network first so updates land; the cache is the offline fallback
    e.respondWith(fetch(e.request).then(r=>{if(r.ok){const cp=r.clone();caches.open(V).then(c=>c.put(e.request,cp));}return r;})
      .catch(()=>caches.match(e.request,{ignoreSearch:true}).then(r=>r||(e.request.mode==='navigate'?caches.match(u.pathname.startsWith('/open')?'/open':'/'):undefined))));}
  else if(/fonts\\.(googleapis|gstatic)\\.com$/.test(u.host)){ // fonts: cached copy first, refreshed in the background
    e.respondWith(caches.open(V+'-fonts').then(async c=>{const hit=await c.match(e.request);const net=fetch(e.request).then(r=>{if(r.ok)c.put(e.request,r.clone());return r;}).catch(()=>hit);return hit||net;}));}});
"""%v
(h.parent/'sw.js').write_text(sw)
print('built',len(fam),len(op),'levels',n,'sw',v)
