-- Run once in the Quotal Supabase project (SQL editor). Same pattern as stair_cleaning_scores.
create table if not exists public.orchard_climber_scores (
  id bigint generated by default as identity primary key,
  device_id text not null,
  pid text not null,
  player text not null,
  face int,
  level int not null,
  moves int not null,
  updated_at timestamptz not null default now()
);
create unique index if not exists orchard_climber_scores_uniq on public.orchard_climber_scores (device_id, pid, level);
alter table public.orchard_climber_scores enable row level security;
create policy "orchard read" on public.orchard_climber_scores for select to anon using (true);
create policy "orchard insert" on public.orchard_climber_scores for insert to anon with check (true);
create policy "orchard update" on public.orchard_climber_scores for update to anon using (true) with check (true);
create or replace function public.orchard_touch() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;
create trigger orchard_touch before update on public.orchard_climber_scores for each row execute function public.orchard_touch();
